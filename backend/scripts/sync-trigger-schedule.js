#!/usr/bin/env node
/**
 * Copies the workflow's cron schedule into backend/trigger-schedule.json.
 *
 * The backend needs to know when fan-out is actually invoked, so it can tell an
 * account that is merely idle this slot from one whose schedule can never
 * coincide with the trigger at all. The authority for that is the workflow —
 * but render.yaml sets rootDir: backend, so .github is not deployed and the
 * backend cannot read it at runtime.
 *
 * Hence a generated manifest that lives inside the deployed directory. Two
 * things follow, both deliberate:
 *
 *   - Editing the workflow alone no longer silently changes when posts happen
 *     without the backend knowing. The manifest must be regenerated, and that
 *     is a backend file, so it also triggers a redeploy.
 *   - `--check` fails when the two disagree, so CI catches the drift rather
 *     than production discovering it.
 *
 *   node scripts/sync-trigger-schedule.js          # regenerate
 *   node scripts/sync-trigger-schedule.js --check  # fail if out of date
 */

const fs = require('fs');
const path = require('path');
const { parseCron } = require('../services/cronMatch');

const WORKFLOW = path.join(__dirname, '..', '..', '.github', 'workflows', 'scheduled-post.yml');
const MANIFEST = path.join(__dirname, '..', 'trigger-schedule.json');
const CRON_LINE = /^\s*-\s*cron:\s*['"]?([^'"\n#]+?)['"]?\s*$/gm;

function readWorkflowSchedules() {
  const text = fs.readFileSync(WORKFLOW, 'utf8');
  const found = [...text.matchAll(CRON_LINE)].map((m) => m[1].trim());
  if (!found.length) throw new Error(`No cron schedule found in ${WORKFLOW}`);

  const bad = found.filter((c) => !parseCron(c));
  if (bad.length) {
    throw new Error(
      `Workflow cron ${bad.map((c) => `"${c}"`).join(', ')} cannot be parsed by cronMatch. ` +
      'The scheduler matches accounts against these, so an unreadable one would ' +
      'make every account look unreachable.',
    );
  }
  return found;
}

function readManifest() {
  try {
    return JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
  } catch {
    return null;
  }
}

function build(schedules) {
  return {
    _comment: 'Generated by scripts/sync-trigger-schedule.js. Do not edit by hand.',
    source: '.github/workflows/scheduled-post.yml',
    schedules,
  };
}

function main() {
  const check = process.argv.includes('--check');
  const schedules = readWorkflowSchedules();
  const current = readManifest();

  if (check) {
    if (!current || JSON.stringify(current.schedules) !== JSON.stringify(schedules)) {
      console.error(
        '✗ trigger-schedule.json is out of date.\n' +
        `  workflow: ${JSON.stringify(schedules)}\n` +
        `  manifest: ${JSON.stringify(current?.schedules ?? null)}\n` +
        '  Run: node scripts/sync-trigger-schedule.js',
      );
      process.exit(1);
    }
    console.log(`✓ trigger-schedule.json matches the workflow (${schedules.join(', ')})`);
    return;
  }

  fs.writeFileSync(MANIFEST, `${JSON.stringify(build(schedules), null, 2)}\n`);
  console.log(`Wrote trigger-schedule.json: ${schedules.join(', ')}`);
}

if (require.main === module) main();

module.exports = { readWorkflowSchedules, readManifest, MANIFEST, WORKFLOW, CRON_LINE };
